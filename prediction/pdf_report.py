from reportlab.lib.pagesizes import A4
from datetime import datetime
from reportlab.lib import colors
from reportlab.lib.styles import (
    getSampleStyleSheet,
    ParagraphStyle,
)
from reportlab.lib.enums import TA_CENTER
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
)
from reportlab.lib.units import inch


def generate_prediction_report(
    response,
    username,
    month,
    prediction,
    estimated_bill,
    consumption_level,
    top_energy_factors,
    recommendations,
    prediction_id=None,
):
    """
    Generate a professional downloadable PDF prediction report.
    """

    pdf = SimpleDocTemplate(
        response,
        pagesize=A4,
        rightMargin=40,
        leftMargin=40,
        topMargin=40,
        bottomMargin=40,
    )

    styles = getSampleStyleSheet()

    # ---------------------------------------------------------
    # PDF STYLES
    # ---------------------------------------------------------

    title_style = ParagraphStyle(
        "ReportTitle",
        parent=styles["Title"],
        alignment=TA_CENTER,
        fontSize=20,
        leading=25,
        textColor=colors.HexColor("#123047"),
        spaceAfter=8,
    )

    subtitle_style = ParagraphStyle(
        "ReportSubtitle",
        parent=styles["BodyText"],
        alignment=TA_CENTER,
        fontSize=10,
        leading=14,
        textColor=colors.HexColor("#4b6475"),
        spaceAfter=4,
    )

    generated_style = ParagraphStyle(
        "GeneratedStyle",
        parent=styles["BodyText"],
        alignment=TA_CENTER,
        fontSize=9,
        leading=13,
        textColor=colors.HexColor("#71808c"),
        spaceAfter=12,
    )

    heading_style = ParagraphStyle(
        "ReportHeading",
        parent=styles["Heading2"],
        fontSize=14,
        leading=18,
        textColor=colors.HexColor("#123047"),
        spaceBefore=16,
        spaceAfter=9,
    )

    normal_style = ParagraphStyle(
        "ReportNormal",
        parent=styles["BodyText"],
        fontSize=10,
        leading=15,
        textColor=colors.HexColor("#263746"),
    )

    small_style = ParagraphStyle(
        "SmallText",
        parent=styles["BodyText"],
        fontSize=8.5,
        leading=12,
        textColor=colors.HexColor("#526674"),
    )

    result_style = ParagraphStyle(
        "ResultStyle",
        parent=styles["BodyText"],
        alignment=TA_CENTER,
        fontSize=15,
        leading=19,
        textColor=colors.HexColor("#0b7285"),
    )

    footer_style = ParagraphStyle(
        "FooterStyle",
        parent=styles["BodyText"],
        alignment=TA_CENTER,
        fontSize=8,
        leading=11,
        textColor=colors.HexColor("#71808c"),
    )

    story = []

    generated_datetime = datetime.now().strftime(
        "%d %b %Y, %I:%M %p"
    )

    # ---------------------------------------------------------
    # REPORT HEADER
    # ---------------------------------------------------------

    story.append(
        Paragraph(
            "Smart Household Electricity<br/>"
            "Consumption & Bill Prediction Report",
            title_style,
        )
    )

    story.append(
        Paragraph(
            "Smart Energy Analytics • Household Electricity Prediction",
            subtitle_style,
        )
    )

    story.append(
        Paragraph(
            "Generated By: Smart Household Electricity "
            "Consumption & Bill Prediction System",
            subtitle_style,
        )
    )

    story.append(
        Paragraph(
            f"Report Generated: {generated_datetime}",
            generated_style,
        )
    )

    # Header separator
    header_line = Table(
        [[""]],
        colWidths=[7.1 * inch],
        rowHeights=[2],
    )

    header_line.setStyle(
        TableStyle(
            [
                (
                    "BACKGROUND",
                    (0, 0),
                    (-1, -1),
                    colors.HexColor("#0ea5a4"),
                ),
            ]
        )
    )

    story.append(header_line)
    story.append(Spacer(1, 12))

    # ---------------------------------------------------------
    # PREDICTION DETAILS
    # ---------------------------------------------------------

    story.append(
        Paragraph(
            "Prediction Details",
            heading_style,
        )
    )

    details = [
        ["Username", str(username)],
        ["Month", str(month)],
        [
            "Prediction ID",
            f"#{prediction_id}"
            if prediction_id
            else "—",
        ],
        [
            "Predicted Consumption",
            f"{float(prediction):.2f} kWh",
        ],
        [
            "Estimated Monthly Bill",
            f"₹{float(estimated_bill):.2f}",
        ],
        [
            "Consumption Level",
            str(consumption_level),
        ],
    ]

    details_table = Table(
        details,
        colWidths=[
            2.3 * inch,
            3.5 * inch,
        ],
    )

    details_table.setStyle(
        TableStyle(
            [
                (
                    "BACKGROUND",
                    (0, 0),
                    (0, -1),
                    colors.HexColor("#e8f4f8"),
                ),
                (
                    "BACKGROUND",
                    (1, 0),
                    (1, -1),
                    colors.HexColor("#f8fbfc"),
                ),
                (
                    "GRID",
                    (0, 0),
                    (-1, -1),
                    0.5,
                    colors.HexColor("#c9d7df"),
                ),
                (
                    "FONTNAME",
                    (0, 0),
                    (0, -1),
                    "Helvetica-Bold",
                ),
                (
                    "FONTNAME",
                    (1, 0),
                    (1, -1),
                    "Helvetica",
                ),
                (
                    "FONTSIZE",
                    (0, 0),
                    (-1, -1),
                    10,
                ),
                (
                    "TEXTCOLOR",
                    (0, 0),
                    (-1, -1),
                    colors.HexColor("#263746"),
                ),
                (
                    "VALIGN",
                    (0, 0),
                    (-1, -1),
                    "MIDDLE",
                ),
                (
                    "TOPPADDING",
                    (0, 0),
                    (-1, -1),
                    8,
                ),
                (
                    "BOTTOMPADDING",
                    (0, 0),
                    (-1, -1),
                    8,
                ),
                (
                    "LEFTPADDING",
                    (0, 0),
                    (-1, -1),
                    9,
                ),
                (
                    "RIGHTPADDING",
                    (0, 0),
                    (-1, -1),
                    9,
                ),
            ]
        )
    )

    story.append(details_table)
    story.append(Spacer(1, 8))

    # ---------------------------------------------------------
    # PREDICTION RESULT HIGHLIGHT
    # ---------------------------------------------------------

    story.append(
        Paragraph(
            "Prediction Result",
            heading_style,
        )
    )

    result_data = [
        [
            Paragraph(
                "Predicted Monthly Consumption",
                small_style,
            ),
            Paragraph(
                "Estimated Monthly Electricity Bill",
                small_style,
            ),
        ],
        [
            Paragraph(
                f"<b>{float(prediction):.2f} kWh</b>",
                result_style,
            ),
            Paragraph(
                f"<b>₹{float(estimated_bill):.2f}</b>",
                result_style,
            ),
        ],
    ]

    result_table = Table(
        result_data,
        colWidths=[
            3.55 * inch,
            3.55 * inch,
        ],
    )

    result_table.setStyle(
        TableStyle(
            [
                (
                    "BACKGROUND",
                    (0, 0),
                    (-1, -1),
                    colors.HexColor("#eef9fa"),
                ),
                (
                    "BOX",
                    (0, 0),
                    (-1, -1),
                    0.8,
                    colors.HexColor("#9bd5d8"),
                ),
                (
                    "INNERGRID",
                    (0, 0),
                    (-1, -1),
                    0.5,
                    colors.HexColor("#c9e4e6"),
                ),
                (
                    "ALIGN",
                    (0, 0),
                    (-1, -1),
                    "CENTER",
                ),
                (
                    "VALIGN",
                    (0, 0),
                    (-1, -1),
                    "MIDDLE",
                ),
                (
                    "TOPPADDING",
                    (0, 0),
                    (-1, -1),
                    10,
                ),
                (
                    "BOTTOMPADDING",
                    (0, 0),
                    (-1, -1),
                    10,
                ),
            ]
        )
    )

    story.append(result_table)

    story.append(
        Paragraph(
            "The estimated monthly bill is calculated from the "
            "predicted electricity consumption using the configured "
            "slab-based billing calculation.",
            small_style,
        )
    )

    story.append(Spacer(1, 5))

    # ---------------------------------------------------------
    # TOP ENERGY-CONSUMING FACTORS
    # ---------------------------------------------------------

    story.append(
        Paragraph(
            "Top Energy-Consuming Factors",
            heading_style,
        )
    )

    if top_energy_factors:

        factor_data = [
            [
                "Rank",
                "Factor",
                "Description",
                "Impact",
            ]
        ]

        for index, factor in enumerate(
            top_energy_factors,
            start=1,
        ):

            factor_data.append(
                [
                    str(index),
                    str(
                        factor.get(
                            "name",
                            "",
                        )
                    ),
                    str(
                        factor.get(
                            "description",
                            "",
                        )
                    ),
                    str(
                        factor.get(
                            "impact",
                            "",
                        )
                    ),
                ]
            )

        factor_table = Table(
            factor_data,
            colWidths=[
                0.5 * inch,
                1.5 * inch,
                2.6 * inch,
                1.0 * inch,
            ],
            repeatRows=1,
        )

        factor_table.setStyle(
            TableStyle(
                [
                    (
                        "BACKGROUND",
                        (0, 0),
                        (-1, 0),
                        colors.HexColor("#dff3f4"),
                    ),
                    (
                        "TEXTCOLOR",
                        (0, 0),
                        (-1, 0),
                        colors.HexColor("#123047"),
                    ),
                    (
                        "FONTNAME",
                        (0, 0),
                        (-1, 0),
                        "Helvetica-Bold",
                    ),
                    (
                        "FONTNAME",
                        (0, 1),
                        (-1, -1),
                        "Helvetica",
                    ),
                    (
                        "FONTSIZE",
                        (0, 0),
                        (-1, -1),
                        8,
                    ),
                    (
                        "GRID",
                        (0, 0),
                        (-1, -1),
                        0.5,
                        colors.HexColor("#c9d7df"),
                    ),
                    (
                        "VALIGN",
                        (0, 0),
                        (-1, -1),
                        "TOP",
                    ),
                    (
                        "TOPPADDING",
                        (0, 0),
                        (-1, -1),
                        6,
                    ),
                    (
                        "BOTTOMPADDING",
                        (0, 0),
                        (-1, -1),
                        6,
                    ),
                    (
                        "LEFTPADDING",
                        (0, 0),
                        (-1, -1),
                        5,
                    ),
                    (
                        "RIGHTPADDING",
                        (0, 0),
                        (-1, -1),
                        5,
                    ),
                ]
            )
        )

        story.append(factor_table)

    else:

        story.append(
            Paragraph(
                "No energy-consuming factors available.",
                normal_style,
            )
        )

    # ---------------------------------------------------------
    # PERSONALIZED RECOMMENDATIONS
    # ---------------------------------------------------------

    story.append(
        Paragraph(
            "Personalized Energy-Saving Recommendations",
            heading_style,
        )
    )

    if recommendations:

        for index, recommendation in enumerate(
            recommendations,
            start=1,
        ):

            if isinstance(
                recommendation,
                dict,
            ):

                text = recommendation.get(
                    "text",
                    str(recommendation),
                )

            else:

                text = str(
                    recommendation
                )

            recommendation_data = [
                [
                    Paragraph(
                        f"<b>{index}.</b>",
                        normal_style,
                    ),
                    Paragraph(
                        text,
                        normal_style,
                    ),
                ]
            ]

            recommendation_table = Table(
                recommendation_data,
                colWidths=[
                    0.35 * inch,
                    6.55 * inch,
                ],
            )

            recommendation_table.setStyle(
                TableStyle(
                    [
                        (
                            "BACKGROUND",
                            (0, 0),
                            (-1, -1),
                            colors.HexColor("#f5fafb"),
                        ),
                        (
                            "BOX",
                            (0, 0),
                            (-1, -1),
                            0.4,
                            colors.HexColor("#d4e5e9"),
                        ),
                        (
                            "VALIGN",
                            (0, 0),
                            (-1, -1),
                            "TOP",
                        ),
                        (
                            "LEFTPADDING",
                            (0, 0),
                            (-1, -1),
                            7,
                        ),
                        (
                            "RIGHTPADDING",
                            (0, 0),
                            (-1, -1),
                            7,
                        ),
                        (
                            "TOPPADDING",
                            (0, 0),
                            (-1, -1),
                            7,
                        ),
                        (
                            "BOTTOMPADDING",
                            (0, 0),
                            (-1, -1),
                            7,
                        ),
                    ]
                )
            )

            story.append(
                recommendation_table
            )

            story.append(
                Spacer(1, 5)
            )

    else:

        story.append(
            Paragraph(
                "No personalized recommendations available.",
                normal_style,
            )
        )

    # ---------------------------------------------------------
    # FINAL NOTE
    # ---------------------------------------------------------

    story.append(
        Spacer(1, 18)
    )

    final_note = Table(
        [
            [
                Paragraph(
                    "💡 Energy-saving recommendations are "
                    "generated based on the household information "
                    "and predicted electricity consumption.",
                    small_style,
                )
            ]
        ],
        colWidths=[7.1 * inch],
    )

    final_note.setStyle(
        TableStyle(
            [
                (
                    "BACKGROUND",
                    (0, 0),
                    (-1, -1),
                    colors.HexColor("#eef9fa"),
                ),
                (
                    "BOX",
                    (0, 0),
                    (-1, -1),
                    0.5,
                    colors.HexColor("#b8dfe2"),
                ),
                (
                    "LEFTPADDING",
                    (0, 0),
                    (-1, -1),
                    10,
                ),
                (
                    "RIGHTPADDING",
                    (0, 0),
                    (-1, -1),
                    10,
                ),
                (
                    "TOPPADDING",
                    (0, 0),
                    (-1, -1),
                    8,
                ),
                (
                    "BOTTOMPADDING",
                    (0, 0),
                    (-1, -1),
                    8,
                ),
            ]
        )
    )

    story.append(final_note)

    # ---------------------------------------------------------
    # FOOTER
    # ---------------------------------------------------------

    story.append(
        Spacer(1, 18)
    )

    footer_line = Table(
        [[""]],
        colWidths=[7.1 * inch],
        rowHeights=[1],
    )

    footer_line.setStyle(
        TableStyle(
            [
                (
                    "BACKGROUND",
                    (0, 0),
                    (-1, -1),
                    colors.HexColor("#c9d7df"),
                ),
            ]
        )
    )

    story.append(footer_line)

    story.append(
        Spacer(1, 7)
    )

    story.append(
        Paragraph(
            "Smart Energy Analytics | Electricity Consumption "
            "& Bill Prediction",
            footer_style,
        )
    )

    story.append(
        Paragraph(
            "This report is generated by the Smart Household "
            "Electricity Consumption & Electricity Bill "
            "Prediction System.",
            footer_style,
        )
    )

    # ---------------------------------------------------------
    # BUILD PDF
    # ---------------------------------------------------------

    pdf.build(story)
